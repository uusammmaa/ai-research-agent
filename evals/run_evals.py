"""
Eval harness entry point for the AI Research Agent.

Usage (from the repo root, with venv active):
    python -m evals.run_evals                     # mocked suite only
    python -m evals.run_evals --write-md          # ...and regenerate evals/RESULTS.md
    python -m evals.run_evals --live              # mocked + live suite
    python -m evals.run_evals --live-only         # live suite only
    python -m evals.run_evals --live -n 5         # live suite with 5 jobs
    python -m evals.run_evals --live --judge      # add the LLM claim-support judge
"""

import argparse
import json
import logging
import sys
from datetime import UTC, datetime
from pathlib import Path

from evals import live_cases, mock_cases

RESULTS_PATH = Path(__file__).parent / "results.json"
RESULTS_MD_PATH = Path(__file__).parent / "RESULTS.md"


def summarize(results: list[dict]) -> dict:
    total = len(results)
    passed = sum(1 for r in results if r["passed"])
    grounded = [
        r["grounding"]["groundedness"]
        for r in results
        if r.get("grounding") and r["grounding"]["groundedness"] is not None
    ]
    cited = [
        r["grounding"]["citation_accuracy"]
        for r in results
        if r.get("grounding") and r["grounding"]["citation_accuracy"] is not None
    ]
    costs = [r["cost_usd"] for r in results if r.get("cost_usd") is not None]
    return {
        "total": total,
        "passed": passed,
        "failed": total - passed,
        "mean_groundedness": round(sum(grounded) / len(grounded), 3) if grounded else None,
        "mean_citation_accuracy": round(sum(cited) / len(cited), 3) if cited else None,
        "mean_cost_usd": round(sum(costs) / len(costs), 4) if costs else None,
    }


def _fmt(value, pct: bool = False) -> str:
    if value is None:
        return "n/a"
    if pct:
        return f"{value:.0%}"
    return str(value)


def _results_table(results: list[dict]) -> list[str]:
    lines = [
        "| Case | Expected | Result | Citation acc. | Groundedness | LLM calls (attempts) | Tool calls (attempts) | Repairs | Tokens in / out | Cost |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        g = r.get("grounding") or {}
        lines.append(
            "| {name} | {expected} | {result} | {cit} | {gnd} | {llm} ({llma}) | {tools} ({toola}) | {rep} | {tin:,} / {tout:,} | ${cost:.4f} |".format(
                name=f"`{r['name']}`",
                expected=r["expected"],
                result="PASS" if r["passed"] else "FAIL",
                cit=_fmt(g.get("citation_accuracy"), pct=True),
                gnd=_fmt(g.get("groundedness"), pct=True),
                llm=r.get("llm_calls", 0),
                llma=r.get("llm_attempts", 0),
                tools=r.get("tool_calls", 0),
                toola=r.get("tool_attempts", 0),
                rep=r.get("repairs", 0),
                tin=r.get("input_tokens", 0),
                tout=r.get("output_tokens", 0),
                cost=r.get("cost_usd") or 0.0,
            )
        )
    return lines


def write_results_md(report: dict) -> None:
    mock = report["mock_suite"]
    s = mock["summary"]
    lines = [
        "# Eval results",
        "",
        "Generated by `python -m evals.run_evals --write-md`. The raw report is",
        "`evals/results.json` (gitignored).",
        "",
        "## Mocked suite",
        "",
        f"**{s['passed']}/{s['total']} passed.** No network, no API keys: Claude's responses and the",
        "tool outcomes are scripted (see `evals/fakes.py`), while retries, timeouts, fallbacks,",
        "validation and repair run for real. Token counts are scripted to the shape of a real run",
        "and priced with `agent/pricing.py` (`claude-opus-5-5` unless the case falls back), so the",
        "cost column shows how retries and repairs move cost, not a measured bill.",
        "",
        "Citation accuracy is the share of claims citing a page the run retrieved. Groundedness is",
        "the share whose cited page contains the quote, the statement's numbers and most of its",
        "content words (`evals/grounding.py`). The last three cases plant one bad claim and pass",
        "only if the scorer flags exactly that claim for the right reason.",
        "",
        *_results_table(mock["results"]),
        "",
    ]
    live = report.get("live_suite")
    if live and live["results"]:
        ls = live["summary"]
        lines += [
            "## Live suite",
            "",
            f"**{ls['passed']}/{ls['total']} passed**, mean groundedness "
            f"{_fmt(ls['mean_groundedness'], pct=True)}, mean citation accuracy "
            f"{_fmt(ls['mean_citation_accuracy'], pct=True)}, mean cost ${ls['mean_cost_usd'] or 0:.4f} per run.",
            "",
            *_results_table(live["results"]),
            "",
        ]
    else:
        lines += [
            "## Live suite",
            "",
            "Not included in this table. Run `python -m evals.run_evals --live --write-md` with",
            "`ANTHROPIC_API_KEY` and `TAVILY_API_KEY` set to add measured runs against current",
            "job postings (real tokens, real cost, real groundedness).",
            "",
        ]
    RESULTS_MD_PATH.write_text("\n".join(lines))


def _print_suite(title: str, results: list[dict], summary: dict) -> None:
    print(f"\n{title}: {summary['passed']}/{summary['total']} passed")
    for r in results:
        status = "PASS" if r["passed"] else "FAIL"
        extras = []
        g = r.get("grounding")
        if g and g["groundedness"] is not None:
            extras.append(f"grounded {g['groundedness']:.0%}")
            extras.append(f"cited {g['citation_accuracy']:.0%}")
        if r.get("cost_usd") is not None:
            extras.append(f"${r['cost_usd']:.4f}")
        if r.get("elapsed_seconds") is not None:
            extras.append(f"{r['elapsed_seconds']}s")
        print(f"  [{status}] {r['name']}" + (f"  ({', '.join(extras)})" if extras else ""))
        if not r["passed"]:
            print(f"         checks: {r['checks']}  error: {r.get('error_message')}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--live", action="store_true", help="also run the live suite")
    parser.add_argument("--live-only", action="store_true", help="skip mocked suite, run live only")
    parser.add_argument("-n", type=int, default=3, help="number of live job URLs to test")
    parser.add_argument("--judge", action="store_true", help="LLM-judge claim support (live only)")
    parser.add_argument("--write-md", action="store_true", help="regenerate evals/RESULTS.md")
    args = parser.parse_args()
    if args.write_md and args.live_only:
        parser.error("--write-md needs the mocked suite; use --live --write-md instead")
    # Retry and fallback warnings are expected in the mock suite; keep output readable.
    logging.basicConfig(level=logging.ERROR)

    run_live = args.live or args.live_only
    mock_results = [] if args.live_only else mock_cases.run_all()
    live_results = live_cases.run_all(args.n, judge=args.judge) if run_live else []

    report = {
        "generated_at": datetime.now(UTC).isoformat(),
        "mock_suite": {"summary": summarize(mock_results), "results": mock_results},
        "live_suite": {"summary": summarize(live_results), "results": live_results}
        if run_live
        else None,
    }

    RESULTS_PATH.write_text(json.dumps(report, indent=2, default=str))
    if args.write_md:
        write_results_md(report)

    if mock_results:
        _print_suite("Mocked suite", mock_results, report["mock_suite"]["summary"])
    if report["live_suite"]:
        _print_suite("Live suite", live_results, report["live_suite"]["summary"])

    print(f"\nResults written to {RESULTS_PATH}")
    if args.write_md:
        print(f"Results table written to {RESULTS_MD_PATH}")

    any_fail = any(not r["passed"] for r in mock_results + live_results)
    sys.exit(1 if any_fail else 0)


if __name__ == "__main__":
    main()
